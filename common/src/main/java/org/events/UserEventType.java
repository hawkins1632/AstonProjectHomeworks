package org.events;

/**
 * Тип события пользователя.
 * <p>
 * Определяет, какое действие произошло с пользователем, и используется
 * консьюмерами для выбора соответствующей бизнес-логики обработки.
 */
public enum UserEventType {
    /**
     * Пользователь создан.
     */
    CREATED,

    /**
     * Данные пользователя обновлены.
     */
    UPDATED,

    /**
     * Пользователь удалён.
     */
    DELETED
}
